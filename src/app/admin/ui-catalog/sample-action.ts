"use server";

import { signedInActor } from "@/presentation/composition";

/**
 * 見本帳で押せるようにするためだけの、何もしない操作。
 *
 * 見本帳の `ActionButton` に本物の操作をつなぐと、部品を見に来ただけの人が
 * 押しただけで実データが動く。かといって `action` を空にすると、
 * 押しても送信そのものが起きず、**押した感じの見え方**（送信中の様子や
 * 二度押しの扱い）を確かめられない。何も起きないが送信は起きる、を用意する。
 *
 * 何もしないのに門を通すのは、**操作は画面と別に叩ける**からである。
 * 見本帳の画面はログインしないと開けないが、この操作の URL は画面を開かずに
 * 呼べる。「中身が空だから素通しでよい」を一度認めると、
 * 次に中身が入った日も素通しのまま残る。
 */
export async function sampleAction(): Promise<void> {
  await signedInActor();
  // ここから先では何もしない。足した瞬間に、見本が本番になる。
}
