/**
 * フォームが送るが、人には見せない値。
 *
 * 「この操作がどのレコードに向けたものか」「どの意図で押されたか」を
 * サーバへ一緒に渡すためのもの。画面には何も出ない。
 *
 * --- なぜ部品にしたか（2026-08-22 / ah-brd）---
 *
 * 元は隠し入力欄の宣言を **21 ファイルが各々書いていた**（50 箇所）。
 * 動きは正しかったが、次の 2 つが起きる。
 *
 *   1. 隠す指定を書き忘れた 1 箇所が、画面に空の入力欄として出る。
 *      見えている欄は触れてしまうので、利用者が値を書き換えられる。
 *   2. 隠し値の扱いを変えたい日（例: すべて読み取り専用にする、
 *      空文字を弾く）に、50 箇所を直すことになる。1 箇所でも漏れれば、
 *      漏れた画面だけ古い作法のまま残る。
 *
 * 部品にすると、**書き忘れようがなくなる**。隠す指定を呼び出し側が持たないため。
 *
 * --- 段（層）---
 *
 * 事業の決めごとを 1 つも知らない。何の値かも、どの操作に付くかも、
 * 呼び出し側が決める。よって primitives に置く。
 *
 * --- 入力欄（`Field`）との違い ---
 *
 * `Field` は人が値を入れる欄。こちらは**人が触らない値**を運ぶだけで、
 * ラベルも検証も持たない。名前が似ているので、迷ったら
 * 「利用者がこの値を変えられるべきか」で選ぶ。変えられるなら `Field`。
 */
export type FormValueProps = {
  /** サーバ側が受け取るときの名前。フォームの中で一意でなくてよい（同名の複数送信は配列になる）。 */
  readonly name: string;
  /** 送る値。数値を渡す用途があるので `number` も受ける。 */
  readonly value: string | number;
};

export function FormValue({ name, value }: FormValueProps) {
  // このファイルだけが隠し入力欄を宣言する。他所に同じ行を書かない。
  return <input type="hidden" name={name} value={value} readOnly />;
}
