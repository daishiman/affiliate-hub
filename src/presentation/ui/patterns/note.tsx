/**
 * 注記。本文より一段弱く出す、独立した段落。
 *
 * **なぜ在るか。** `.linkNote`（`admin.module.css:73` / `signin.module.css:44`）は
 * 宣言を 2 つしか持っていない——`font-size: var(--text-sm)` と
 * `color: var(--color-text-muted)` だけである。**構造も余白も表示種別も持たない。**
 * だから同じクラスが `<p>` に付けば塊として、`<span>` に付けば行内として出る。
 * **出方を決めているのは要素であって、クラスではない。**
 *
 * つまり `.linkNote` は「役の名前」ではなく「字の見た目の名前」だった。
 * 小さい灰色にしたいものなら何にでも当たり、実際に当たっていた
 * （残課題 147 / 148。詳しくは下の「ここに寄せてはいけないもの」）。
 * この部品の値打ちは余白でも大きさでもなく、**役に名前が付くこと**にある。
 * 名前があれば、当てる前に一度「これは注記か？」が問われる。
 *
 * **余白は宣言しない。これは決めた結果であって、書き忘れではない。**
 * いまの 43 箇所は余白ゼロで出ている（Preflight が `p` の既定余白を 0 にし、
 * `.linkNote` も余白を宣言していないため）。実物を描いて見る手立てが無い以上、
 * **現状を写すことが唯一の実測に基づく選択で、足すのは推測である。**
 * 間隔は親側の `gap` が持っている。要ると分かった日に、ここ 1 箇所で足せる。
 *
 * **`className` は受け取らない。** 受け取れる形にすると、呼び出し側が
 * 「この 1 箇所だけ少し空ける」を足し始める。**43 箇所に散った余白は、
 * 余白ゼロで揃っているいまの状態より悪い。**`SectionHeading` と同じ理由。
 *
 * **ここに寄せてはいけないものが 2 種類ある。**`.linkNote` の残り 41 箇所は
 * 見た目が同じでも役が違うので、揃えるために通さないこと。
 *
 *   - **一覧の行の説明（`<li>` の中の `<span>`）。当時 36 箇所と書いたが、
 *     実測は 35 だった。**対の片割れだけを部品にすると、一覧の 1 行が
 *     部品と生クラスの継ぎ目で割れる。
 *
 *     **2026-08-21 に済んだ**（残課題 156）。`.linkList` ごと `StackedList` /
 *     `StackedRow` へ上げ、行の注記は `StackedRow` の `note` が受け持っている
 *     （26 ファイル・`StackedList` 51・`StackedRow` 61・note 35）。
 *     だからここへ寄せてはいけないのは変わらないが、理由が
 *     「まだ上げていないから」から「**別の部品が持っているから**」に変わった。
 *   - **行内の小書き（5 箇所、`<li>` の外の `<span>`）。**
 *     とくに `admin/feedback/page.tsx` の 1 件は `<label>` の中にあり、
 *     **チェックボックスのラベル文そのもので、注記ではない**。
 *     ここへ通すと表示は合ったまま意味が嘘になる（残課題 148）。
 *     見た目の整理とは別の問題なので、別に直すこと。
 *
 * **3 種類目は、この部品自身が破っていた。**上の 2 つは外から寄せてはいけないものだが、
 * こちらは**部品にした後で中に残っていた誤り**である。42 箇所のうち 6 箇所が
 * `<Note><Link>…を見る</Link></Note>` の形で、**注記ではなく行き先**だった。
 * `SeeAlso`（`see-also.tsx`）へ移してある（残課題 152）。
 *
 * **部品化は役を正さない。**むしろ、`.linkNote` という生クラスだった頃は
 * 「これは本当に注記か」を疑う余地があったのに、**部品の名前が役を主張するので
 * 疑う理由が消える**。「`Note` を使っている＝注記である」と読めてしまう。
 * だから**役を疑う仕事は、部品にした後のほうが重い。**
 *
 * **なぜ primitives ではなく patterns に在るか。**役の重さの話ではなく、
 * **同じ日に `ui.module.css` を別の担当が持っていた**ため（押しどころの下限を
 * 6 本入れる作業）。同じファイルを 2 人で触ると、どちらの直しが赤を消したのかが
 * 分からなくなる。**置き場を分けた理由が分担であることを、ここに書いておく**——
 * 次に見た人が「なぜ primitives でないのか」を役の重さで説明し直さないように。
 *
 * 見張りは `tests/ui/note-role.test.ts`。
 */
export function Note({ children }: { readonly children: ReactNode }) {
  return <p className={styles.note}>{children}</p>;
}
