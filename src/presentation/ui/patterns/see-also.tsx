import type { ReactNode } from "react";
import styles from "./patterns.module.css";

/**
 * 「続きはあちらで見られる」の案内。節の末尾に置く、行き先 1 本だけの段落。
 *
 * **なぜ在るか。** `Note` の使用箇所 42 のうち 6 箇所が、この形だった:
 *
 *     <Note><Link href="/admin/personas">書き手と読者像を見る</Link></Note>
 *
 * **これは注記ではない。**注記は「いま見えているものの読み方」を言うが、
 * こちらは「ここには無い、あちらへ行け」と言っている。**中身が文ではなく行き先である。**
 * `Note` の doc は「見た目が同じでも役が違うので揃えるために通さないこと」と
 * 書いていて、**部品自身がその戒めを 6 箇所で破っていた**（残課題 152）。
 *
 * **見つけたのは `audit-ABN` で、見つかった理由は押しどころの下限である。**
 * `.note > a { min-height: 44px }` と書こうとすると、文の中に埋まっているリンク
 * 2 本（`distribution/[publication]` と `sites`）にも当たって行が崩れる。
 * **1 本の CSS 規則が、片方には正しく片方には誤りになる**——これが、
 * この 6 箇所が別の役である何よりの証拠だった。**役が違うかどうかは、
 * 名前の座りではなく「同じ扱いが両方に効くか」で決まる。**
 *
 * **なぜ `href` を受け取らないか。** `primitives` と `patterns` は
 * `next/link` を取り込まない（取り込んでいるのは `templates` の 3 ファイルだけ）。
 * `WorkBoard` が `renderLink` を引数で受けているのは同じ理由である。
 * だからこの部品は入れ物だけを持ち、**行き先は呼び出し側が入れる。**
 * 中身が本当にリンク 1 本かは型では縛れないので、`tests/ui/note-role.test.ts` が見る。
 *
 * **`className` は受け取らない**（`Note` / `SectionHeading` と同じ理由）。
 *
 * **見た目は `.note` と同じ 2 宣言を持つ。写しであって、共有ではない。**
 * いまの 6 箇所は小さい灰色で出ているので、そのまま写した——
 * **見た目を変える判断は、実物を描いて見る手立てが無い以上できない。**
 * 同じ値を 2 か所に書いているのは無駄に見えるが、**別々に動かせることが要件**である。
 * 押しどころの下限は `.seeAlso` の側にだけ足せばよく、`.note` は巻き込まれない。
 * まとめた瞬間に、その「巻き込まれない」が失われる。
 *
 * **ここに寄せてはいけないもの。**文の中に埋まったリンク（2 箇所）は `Note` のまま。
 * 「〜を見る」と書いてあっても、**前後に連れの文が在るなら、それは行き先ではなく文である。**
 *
 * 見張りは `tests/ui/note-role.test.ts`。
 */
export function SeeAlso({ children }: { readonly children: ReactNode }) {
  return <p className={styles.seeAlso}>{children}</p>;
}
