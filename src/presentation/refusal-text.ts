import type { DomainError } from "@/domain/shared";
import { maskExistence } from "@/presentation/http/error-response";

/**
 * 断ったときに画面へ出す文を作る。
 *
 * --- なぜ 1 か所に寄せるのか ---
 * 各操作はそれぞれ `suggestedAction ?? message` と書いていた。
 * 次に何をすればよいかだけを出す形で、**次にすることが書いてある限り、
 * 何が起きたかは画面から消える**。
 *
 * 記録を残せなかったときの断りが入って、この差が実害になった。
 * 「ブログは作られていて読む人からも見えます。ただし記録を残せませんでした」の
 * 前半が落ちると、押した人は作られていないと思って名前を変えてもう一度作り、
 * 同じブログが 2 本並ぶ。金額の修正も同じで、直っているのに直しに戻る。
 *
 * **済んだことと、次にすることは、どちらも要る。**
 * 片方を落とす判断を各操作でやり直せる状態にしておくと、
 * 新しい操作を足すたびに同じ抜け方が起きる。
 *
 * `admin/` ではなく `presentation/` 直下に置いてあるのは、
 * 押して何かが変わる操作が管理画面だけではないため
 * （読者側の問い合わせも同じ）。片側だけの決まりにすると、
 * もう片側で同じ抜け方がもう一度生まれる。
 */
export function refusalText(error: DomainError): string {
  /*
   * --- 存在を隠すのは、ここでもやる（2026-08-24 に足した） ---
   *
   * `maskExistence()` は REST（`errorResponse()`）と MCP には入っていたが、
   * **画面の経路には入っていなかった**。入口は 4 つあると分かっていて、
   * 2 つで止まっていた。
   *
   * 画面はその 2 つより漏れやすい。番号を見なくてよく、本文がそのまま目に入る。
   * 他所の作業場所の ID を入れると「記事 が見つかりません。」、
   * 無い ID を入れると「記事 が見つかりません (id: obj-9999)。」と出ていたので、
   * ID を 1 つずつ試して括弧の有無を見るだけで、他所に何があるかが読めた。
   *
   * 潰す規則そのものはここに書かない。`maskExistence()` を呼ぶ。
   * 規則を写すと、片方だけが古くなる。
   */
  const shown = maskExistence(error);
  return shown.suggestedAction === undefined
    ? shown.message
    : `${shown.message}\n${shown.suggestedAction}`;
}

/**
 * **ログインしていない人**へ返す断り。
 *
 * これは `refusalText()` とは別物である。あちらは預かり所まで届いた操作が
 * 判断の結果として断られたときの文で、こちらは**届く前に断った**ときの文である。
 * 同じ関数にまとめると、「判断してもらえなかった」と「判断された結果だめだった」が
 * 画面で同じ顔をする。押した人が次にすることが変わるので、分けてある。
 *
 * 文を 1 か所に寄せてあるのは、操作ごとに書き起こすと**同じ状況で違う文が出る**ため。
 * 違う文が出ると、押した人は違うことが起きたと受け取り、
 * 「さっきは通ったのに」と操作を変えて試し始める。
 *
 * `what` には**その操作で何ができないか**を入れる（「記事の公開」など）。
 * 何ができないかを書かずに「できません」とだけ出すと、
 * どこまで進んだのかが分からず、やり直してよいのかも決められない。
 */
export function notSignedInText(what: string): string {
  return `ログインしていないため、${what}はできません。\nログインしてからやり直してください。`;
}
