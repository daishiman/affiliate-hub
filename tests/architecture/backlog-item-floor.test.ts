/**
 * @tier 1
 * @req REQ-TS17
 * @types boundary, equivalence
 *
 * 残課題 78 番の項目が、消えていないこと。
 *
 * --- REQ-TS17 は借用である（読む前に知っておくこと）---
 *
 * **この検査に合う要件は、まだ存在しない。**
 * REQ-TS17 は「**0 を主張する検査に**母集団の床を同居させる」で、
 * この検査は 0 を主張していない（下限そのものである）。
 * したがって「REQ-TS17 に紐づく検査が 2 本ある」と数えられるが、
 * **片方は TS17 が求めたものではない。**
 * 借りた側は正直に近い名前を選んでいるので悪意も不注意も無く、
 * 次に TS17 の充足を数える人は、中身を読むまで別物だと知りようがない。
 *
 * 外そうとしたが外せなかった。`TRACEABILITY_MAX_UNLINKED = 28` に対して
 * 実測（`node scripts/traceability.mjs --check`、単位はテストファイル数）が
 * **28** で遊びが 0 なので、要件未割当にすると 29 になって赤くなる。
 * 上限は上げない。既存の要件の文言をこの検査に合うように広げるのも採らない
 * （「仕様を実装に合わせる訂正」で、いちばん通りやすい形の要件削除になる）。
 * 要件は、要件それ自体の理由で立てるときに立てる。
 *
 * **目録に書いただけの限界は、検査を読む人には届かない。**だからここにも書く。
 * 詳細は `docs/product/backlog.md` の 78 番 (74)。
 *
 * --- なぜ要るのか ---
 *
 * 78 番は **1 行 88,946 文字（UTF-8 で 212,909 バイト、2026-08-20 (94) 追記時点）**である。
 * この数を出したコマンドは
 * `python3 -c "…len(row) / len(row.encode())"`（78 番の行だけを取り出して測る）。
 * **数にコマンドと単位を併記する**（⑰）。hash も同じ扱いにする（(81)）。
 * 調整役の 157,370 と当方の 64,903 は食い違いではなく、**バイトと文字という単位の違い**だった。
 * 日本語は 1 文字 3 バイトなので、同じものを測って 2.4 倍ずれる。
 * 数だけを渡すと単位が落ちる——**数に単位を付けずに突き合わせると、一致も不一致も判定できない。**
 * 段落を 1 行で書いているので、
 * 追記のたびに差分は「64,000 文字を消して 65,000 文字を書いた」と出る。
 * **差分は行単位なので、既存の内容が消えても差分では区別できない。**
 * 規律は「消さない」なのに、**守れているかを確かめる手段が差分の側に無い。**
 *
 * この文書は、失われることを防ぐために作った目録である。
 * その目録が、失われても分からない形式で保管されていた。
 *
 * 2026-08-19 に調整役が (60)〜(70) の実在を 1 件ずつ確認して無事だったが、
 * **確認できたのは番号を知っていたからである。知らない番号が消えたら誰も気づかない。**
 *
 * （改行の入れ直しは統合時に調整役が一度だけ行う。ここでは触らない。）
 *
 * --- 数え方（先に定義する）---
 *
 * 1. **行内コード（`` ` `` で囲まれた部分）を先に外す。**
 *    外さずに `(\d{1,3})` で拾うと、`vi.advanceTimersByTime(999)` のような
 *    **引用文の中の数**を項目番号として拾う（調整役が実際にこれで最大 999 を得た）。
 *    78 番の (58)「境界の値が小さいほど、母集団のどこかに必ず同じ数が居る」と
 *    (69)「除外を足すのは無限に続き、包含を名指しするのは有限で終わる」が、
 *    **この検査自身に効いている**——だから除外条件を並べるのではなく、
 *    項目番号の**形を名指し**する（丸数字、または `(N)` の直後が `**`）。
 * 2. 番号は 2 系統ある。族 I の古い番号が丸数字 ①〜㊿（1〜50）、
 *    その続きが `(51)` 以降の括弧番号。**合わせて 1 から始まる通し番号**である。
 * 3. 拾った番号そのものを、失敗時に必ず出す。**件数だけを出さない。**
 *    件数だけだと、拾い方が壊れて別のものを数えていても数は揃う。
 *
 * --- 下限だけでなく欠番も見る理由 ---
 *
 * 件数の下限だけだと、**古い項目を 1 つ消して新しい項目を 1 つ足せば通る。**
 * 78 番でいちばん失いたくないのは、いちばん古い項目である
 * （新しいものは書いた本人がまだ覚えている）。
 * 通し番号に欠けが無いことを見れば、消えた 1 件がその番号で名指しできる。
 *
 * `form2-population-floor.test.ts` が「上限だけでは検査そのものを消せば緑になるので
 * 下限を対で置く」と書いているのと同じ形で、**逆向きの 2 つを揃えるのが本体**である。
 *
 * --- この検査の限界（先に書く）---
 *
 * 番号が付いている項目しか見ていない。番号の無い前置き
 * （「族 I / 族 II のどちらの目で読むか」の断り書きなど）が消えても気づけない。
 * また、**項目の中身が空になっても番号が残っていれば通る。**
 * ここが守るのは「項目が在ること」までで、「中身が在ること」ではない。
 */
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

/**
 * 78 番の項目数の下限。**上げる方向にしか動かさない。**
 * 2026-08-20 の実測は 94（丸数字 50 + 括弧番号 44）。
 * **この下限は件数なので、中身の入れ替わりを捕まえない**（78 番 ㉚ と (94)）。
 * 1 件消して 1 件足せば数は揃う。同一性の側は「通し番号に欠けが無い」検査が
 * 部分的に見ているだけで、**番号を保ったまま本文を差し替える形は今も見えない。**
 *
 * もう 1 つ、この検査自身が 78 番 (93) の形を持っている。
 * **この下限を 94 から 1 へ下げても、検査は緑のまま通る。**
 * 「門が動くこと」は見ているが、「**門が動かされていないこと**」を見る assert が無い。
 * (93) の直し方はハードコードの実数で下限そのものを縛ることだが、
 * **記録に留めて直していない**（測定と着工を同じ区間に入れないため。統合時に起票）。
 * **この丸数字の拾い方は符号位置の範囲なので、NEGATIVE CIRCLED /
 * DINGBAT NEGATIVE CIRCLED の類を拾わない。**調整役が人工の 3 件で対照を取り、
 * 文字名照合の側は 3 件とも拾い、この範囲は 0 件だった（実物には 1 つも無い）。
 * **50 の一致は「両方とも同じくらい目が粗いから一致した」のではない**が、
 * この検査の側だけを見ると、その 3 種は今も見えない。
 * この数え方は括弧番号の側だけを見ると調整役の再測と**同じ正規表現**なので、
 * 二重に数えたことにならない（78 番 (87)）。独立しているのは丸数字の側だけである。
 *
 * 項目の中で箇条書きをするときは `(a)(b)(c)` を使い、丸数字を使わないこと。
 * 丸数字は項目番号そのものなので、箇条書きに使うと数え方が曖昧になる
 * （いまは重複を潰しているので数は動かないが、動かないことに頼らない）。
 */
const BACKLOG_78_MIN_ITEMS = 94;

const ROW_PREFIX = "| 78 ";

function row78(): string {
  const text = readFileSync("docs/product/backlog.md", "utf8");
  const line = text.split("\n").find((l) => l.startsWith(ROW_PREFIX));
  if (line === undefined) throw new Error("残課題 78 番の行が見つからない");
  // 行内コードを先に外す（引用文の中の数を項目番号として拾わないため）
  return line.replace(/`[^`]*`/g, " ");
}

/** 丸数字 → 数。①〜⑳ = 1〜20、㉑〜㉟ = 21〜35、㊱〜㊿ = 36〜50。 */
function circledValue(ch: string): number | null {
  const c = ch.codePointAt(0);
  if (c === undefined) return null;
  if (c >= 0x2460 && c <= 0x2473) return c - 0x2460 + 1;
  if (c >= 0x3251 && c <= 0x325f) return c - 0x3251 + 21;
  if (c >= 0x32b1 && c <= 0x32bf) return c - 0x32b1 + 36;
  return null;
}

/** 拾った項目番号と、拾った文字列そのもの。件数だけを返さない。 */
function items(): { n: number; token: string }[] {
  const line = row78();
  const out: { n: number; token: string }[] = [];
  for (const m of line.matchAll(/[①-⑳㉑-㉟㊱-㊿]/g)) {
    const n = circledValue(m[0]);
    if (n !== null) out.push({ n, token: m[0] });
  }
  // 定義は `(N) **…` の形。参照（「→ (57)」など）は ** が続かないので入らない。
  for (const m of line.matchAll(/\((\d{1,3})\)\s*\*\*/g)) {
    out.push({ n: Number(m[1]), token: m[0].trim() });
  }
  const seen = new Set<number>();
  return out.filter((x) => (seen.has(x.n) ? false : (seen.add(x.n), true)));
}

describe("残課題 78 番の目録", () => {
  it("項目が下限を割っていない（1 行が長すぎて、消えても差分に出ないため）", () => {
    const found = items();
    const tokens = found.map((x) => x.token).join(" ");
    expect(
      found.length,
      `拾った ${found.length} 件: ${tokens}\n（件数だけでなく拾った文字列を出している。拾い方が壊れると、数が揃っていても中身が別物になる）`,
    ).toBeGreaterThanOrEqual(BACKLOG_78_MIN_ITEMS);
  });

  it("通し番号に欠けが無い（件数の下限だけだと、1 件消して 1 件足せば通るため）", () => {
    const found = items().map((x) => x.n);
    const max = Math.max(...found);
    const missing = [];
    for (let n = 1; n <= max; n += 1) if (!found.includes(n)) missing.push(n);
    expect(missing, `欠けている項目番号: ${missing.join(", ")}（最大 ${max}）`).toEqual([]);
  });
});
